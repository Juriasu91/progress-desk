const ctxBar = (pct: number, width: number): string => {
  const filled = Math.round((width * pct) / 100)
  return '█'.repeat(filled) + '░'.repeat(Math.max(0, width - filled))
}

const STATUS_GLYPH: Record<string, string> = { running: '●', done: '✓', failed: '✗', planned: '◷' }

// Opens the agents pane, or closes it when it is up; true when it ends up open.
async function togglePane($: EngineInterface): Promise<boolean> {
  if (leFluff) {
    const isShown = (await read($, shownInLeFluff)) > 0
    await showInLeFluff($, !isShown)
    return !isShown
  }
  const isOpen = (await $.ui.panes()).some(p => p.id === PANE)
  if (isOpen) {
    await $.ui.close({ id: PANE })
    return false
  }
  const at = await $.clock.now()
  await update($, now, () => at)
  await $.ui.open({ id: PANE, title: tr().pane })
  return true
}

async function autoOpen($: EngineInterface, key: string): Promise<void> {
  const p = await read($, panel)
  if (p.autoOpenedFor === key) return
  await update($, panel, prev => ({ ...prev, autoOpenedFor: key }))
  if (leFluff) {
    // A panel that is shown already keeps its number, so Le Fluff does not bring back one that was hidden there.
    if (!(await read($, shownInLeFluff))) await showInLeFluff($, true)
    return
  }
  void $.ui.open({ id: PANE, title: tr().pane })
}

// ---------------------------------------------------------------------------
// Le Fluff: a chat inside Le Fluff is a terminal, which cannot draw the bar's drawing.
// Le Fluff names a folder in LEFLUFF_BAND and shows the drawings it finds there under the chat.
// So there this mod writes the desktop's row into that folder, and draws no row in the terminal.
//
// The Agents panel goes the same way, and Le Fluff shows it beside the chat. `/desk` and the opening when a subagent starts do not open a
// pane there, because the terminal would draw the panel as text as well. They mark the panel as
// shown (shownInLeFluff), and the drawings the desktop gets are handed over beside the bar.

// Module scope is fine here: session.start sets these again on every (re)load.
let leFluff: string | undefined
// True when Le Fluff draws the buttons this mod hands over and tells it the clicks (LEFLUFF_BAND_BUTTONS).
// An older Le Fluff shows only the drawings, so there the finished bar still goes away by itself.
let hasButtons = false
// The band's width in terminal columns, as the terminal last drew it.
let columns = 100
let handed = ''
// The number of the last opening, so the next one always gets a higher number.
let lastShown = 0

// Le Fluff is always dark, whatever the system is set to.
const alwaysDark = (source: string): string => source.replaceAll('@media (prefers-color-scheme: dark)', '@media all')

// The panel beside a chat in Le Fluff: about as wide as the desktop's pane at its usual size.
const SIDE_W = 440
// Le Fluff reads at most 200 rows and 2 MB from a mod, and a crab in costume is up to about 9 KB.
// So the panel stops at 120 rows, and the rows at its end are left out.
const SIDE_ROWS = 120

type SideRow = { svg: string; width: number; height: number; alt: string } | { text: string } | { button: LeFluffButton }

// Opens the panel in Le Fluff, or closes it. Each opening gets its own number, and Le Fluff shows
// a panel again that was hidden there once the number changes.
async function showInLeFluff($: EngineInterface, isShown: boolean): Promise<void> {
  const at = await $.clock.now()
  await update($, now, () => at)
  if (isShown) lastShown = Math.max(at, lastShown + 1)
  await update($, shownInLeFluff, () => (isShown ? lastShown : 0))
  await handOver($)
}

// A button Le Fluff draws for this mod. A click comes back through PRESSES (see readPresses).
type LeFluffButton = { id: 'agents' | 'dismiss' | 'compact' | 'done' | 'close-agents'; label: string }

// The panel as the desktop draws it, with the desktop's buttons: Collapse or Expand in its title
// line, and the Finished head that folds the finished agents away. Its ✕ only closes it, so a ✕
// pressed while Le Fluff still shows a panel that is closed here never opens it again.
async function sideOf(
  $: EngineInterface,
): Promise<{ title: string; shown: number; rows: SideRow[]; buttons: LeFluffButton[]; close: 'close-agents' } | null> {
  const shown = await read($, shownInLeFluff)
  if (!shown) return null
  const s = tr()
  const list = await read($, agents)
  const f = await read($, flow)
  const p: Panel = await read($, panel)
  const at = Math.max(await read($, now), ...list.map(a => a.startedAt), 0)
  const running = list.filter(a => a.status === 'running').reverse()
  const finished = list.filter(a => a.status !== 'running').reverse()
  const planned = plannedOf(f, list)
  const t = totals(list, at)
  const title = f && !f.isFinished ? f.title : ''
  const summary = `≈${fmtCost(t.cost)}, ${fmtTokens(t.tokens)} ${s.tokensWord}, ${fmtTime(t.time)}`
  const drawing = (source: string, height: number, alt: string): SideRow => ({ svg: alwaysDark(source), width: SIDE_W, height, alt })
  const side = (rows: SideRow[]) => ({
    title: s.pane,
    shown,
    rows: rows.slice(0, SIDE_ROWS),
    buttons: [{ id: 'compact', label: p.isCompact ? s.expand : s.collapse }] as LeFluffButton[],
    close: 'close-agents' as const,
  })

  if (p.isCompact) return side([drawing(compactSvg(SIDE_W, list, planned, t), 32, `${list.length} ${s.agentsCount}, ${summary}`)])
  const rows: SideRow[] = [drawing(headerSvg(SIDE_W, title, t), headerHeight(title), title ? `${title}: ${summary}` : summary)]
  if (list.length === 0 && planned.length === 0) rows.push({ text: s.empty })
  if (running.length > 0) rows.push({ text: `${s.running} · ${running.length}` })
  for (const a of running) rows.push(drawing(agentSvg(SIDE_W, a, at), 66, `${a.description}: ${modelName(a.model)}, ${s.isRunning}`))
  if (finished.length > 0) rows.push({ button: { id: 'done', label: `${p.isDoneCollapsed ? (isRtl() ? '◂' : '▸') : '▾'} ${s.finished} · ${finished.length}` } })
  if (!p.isDoneCollapsed) for (const a of finished) rows.push(drawing(agentSvg(SIDE_W, a, at), 66, `${a.description}: ${modelName(a.model)}, ${s.isFinished}`))
  if (planned.length > 0) rows.push({ text: `${s.planned} · ${planned.length}` })
  for (const pl of planned) rows.push(drawing(plannedSvg(SIDE_W, pl), 46, `${pl.n}. ${pl.title}: ${s.isPlanned}`))
  return side(rows)
}

// Le Fluff notes each click on one of this mod's buttons in this file, as { presses: [{ n, id }] }:
// the newest clicks, each with a higher number. Each number is answered once.
const PRESSES = 'presses/progress-desk.json'
let pressSeen = 0
// One look at a time: a look that is still answering clicks must not meet the next one.
let isReading = false
let pressTimer: { cancel: () => void } | null = null

async function pressesOf($: EngineInterface): Promise<{ n: number; id: string }[]> {
  if (!leFluff) return []
  try {
    const saved = JSON.parse(await $.fs.read(`${leFluff}/${PRESSES}`)) as { presses?: unknown }
    if (!Array.isArray(saved.presses)) return []
    return saved.presses.filter((press): press is { n: number; id: string } => Number.isInteger(press?.n) && typeof press?.id === 'string')
  } catch {
    // No click yet, or Le Fluff is writing it right now: the next look reads it.
    return []
  }
}

async function readPresses($: EngineInterface): Promise<void> {
  if (isReading) return
  isReading = true
  try {
    await answerPresses($)
  } finally {
    isReading = false
  }
}

async function answerPresses($: EngineInterface): Promise<void> {
  const fresh = (await pressesOf($)).filter(press => press.n > pressSeen).sort((a, b) => a.n - b.n)
  if (fresh.length === 0) return
  pressSeen = fresh[fresh.length - 1]!.n
  for (const press of fresh) {
    if (press.id === 'agents') await togglePane($)
    else if (press.id === 'close-agents') {
      if (await read($, shownInLeFluff)) await showInLeFluff($, false)
    }
    else if (press.id === 'compact') await update($, panel, prev => ({ ...prev, isCompact: !prev.isCompact }))
    else if (press.id === 'done') await update($, panel, prev => ({ ...prev, isDoneCollapsed: !prev.isDoneCollapsed }))
    else if (press.id === 'dismiss') {
      holdTimer?.cancel()
      holdTimer = null
      await update($, flow, () => null)
    }
  }
  await handOver($)
}

async function handOver($: EngineInterface): Promise<void> {
  if (!leFluff) return
  const f = await read($, flow)
  const rows: { svg: string; width: number; height: number; alt: string; tail: string; buttons: LeFluffButton[] }[] = []
  if (f !== null) {
    const list = await read($, agents)
    const crew = list.length + plannedOf(f, list).length
    const isWorking = list.some(a => a.status === 'running') || (!f.isFinished && f.running > 0)
    // About 8.2 CSS px per column of Le Fluff's terminal; the count of agents stands after the drawing.
    const W = Math.max(180, Math.min(1600, Math.round(columns * 8.2) - 48))
    rows.push({
      svg: alwaysDark(rowSvg(f, W, isWorking)),
      width: W,
      height: H,
      alt: `${f.title}: ${label(f)}, ${Math.round(ratio(f) * 100)}%`,
      // For a Le Fluff that does not draw buttons yet.
      tail: `×${crew}`,
      // As in the desktop: the count opens or closes the Agents panel, and ✕ takes the bar away.
      buttons: [
        { id: 'agents', label: `×${crew}` },
        { id: 'dismiss', label: '✕' },
      ],
    })
  }
  // Rows with a lower order stand higher in Le Fluff's band: the bar comes under the usage limits.
  // A closed panel is left out.
  const side = await sideOf($)
  const text = JSON.stringify({ order: 20, rows, ...(side ? { panel: side } : {}) })
  if (text === handed) return
  handed = text
  try {
    await $.fs.write(`${leFluff}/progress-desk.json`, text)
  } catch {
    // Written again at the next look.
    handed = ''
  }
}

export const register: Register = (on, options) => {
  on('session.start', async ($, e, next) => {
    // Read first, so the terminal draws no row of its own while the rest of the start runs.
    leFluff = (await $.env.get('LEFLUFF_BAND').catch(() => undefined)) || undefined
    hasButtons = !!leFluff && (await $.env.get('LEFLUFF_BAND_BUTTONS').catch(() => undefined)) === '1'
    handed = ''
    const started = await next(e)
    lang = await detectLang($, options.language)
    await $.tool.register({
      name: 'plan',
      description:
        'Draw your to-do list as the progress bar above the prompt. Send every step in order, each pending, in_progress or completed, ' +
        'first when you start a task of 2 or more steps and again whenever a step finishes. Mark the last step completed before your final answer.',
      inputSchema: {
        type: 'object',
        properties: {
          steps: {
            type: 'array',
            description: 'Every step, in order.',
            items: {
              type: 'object',
              properties: {
                text: { type: 'string', description: 'The step in a few plain words.' },
                status: { type: 'string', enum: ['pending', 'in_progress', 'completed'] },
              },
              required: ['text', 'status'],
            },
          },
        },
        required: ['steps'],
      },
      // In front, not behind ToolSearch: a hidden tool never gets called.
      isDeferred: false,
    })
    await $.command.register({
      name: 'desk',
      description: 'Show or hide the panel of subagents: what each is doing, with model, context, cost and time',
    })

    // Ticks the running agents' clocks; quiet when nothing runs.
    $.clock.every(1000, () => {
      void (async () => {
        const list = await read($, agents)
        if (!list.some(a => a.status === 'running')) return
        const at = await $.clock.now()
        await update($, now, () => at)
      })()
    })

    if (leFluff) {
      // Clicks from before this start were answered already.
      pressSeen = Math.max(0, ...(await pressesOf($)).map(press => press.n))
      // A click is looked for often, so a button answers quickly. A start again in the same
      // process, such as after /clear, keeps one look going, not two.
      pressTimer?.cancel()
      pressTimer = hasButtons ? $.clock.every(500, () => void readPresses($)) : null
      // The list, the agents and the width all change the drawing, so it is looked at once a second
      // and written only when it changed.
      $.clock.every(1000, () => void handOver($))
      await handOver($)
      // Takes down a row the terminal drew before this start had read where it runs.
      $.ui.invalidate('ui.render')
    }
    return started
  })

  on('command.run', { command: 'desk' }, async ($, e) => {
    // `/desk open` opens the panel, or brings it forward from behind another tab, without toggling it.
    if ((e.args ?? '').trim() === 'open') {
      if (leFluff) {
        await showInLeFluff($, true)
        return { text: tr().opened }
      }
      const at = await $.clock.now()
      await update($, now, () => at)
      await $.ui.open({ id: PANE, title: tr().pane })
      return { text: tr().opened }
    }
    const isOpen = await togglePane($)
    return { text: isOpen ? tr().opened : tr().closed }
  })

  on('tool.call', async ($, e, next) => {
    const tool = e.tool as string
    const args = e as unknown as Args
    const agentId = e.agentId
    // Only the main chat keeps the bar. A subagent that calls this tool gets an answer instead of an
    // error, because nothing stands behind the tool but this hook.
    if (agentId && tool === OWN_TOOL) return { result: 'Only the main chat keeps a plan. Carry on with your task.' } as never
    // A subagent's call: show what it is doing. A subagent's own to-do list stays off the bar.
    if (agentId) {
      await update($, agents, list => list.map(a => (a.agentId === agentId ? { ...a, stepNote: activity(tool, args) } : a)))
      return next(e)
    }
    if (tool === OWN_TOOL) {
      isListSeen = true
      const steps = nextSteps(tool, await read($, plan), args, undefined)
      if (!steps) return { result: 'Not drawn: send steps as a list of { text, status }.' } as never
      await applySteps($, steps)
      return { result: `Drawn: ${steps.filter(step => step.status === 'completed').length} of ${steps.length} steps done.` } as never
    }
    if (!LIST_TOOLS.has(tool)) {
      const passed = await next(e)
      turnCalls++
      if (isListSeen || isNudged || turnCalls < NUDGE_AFTER || !passed || typeof passed !== 'object' || 'deny' in passed) return passed
      isNudged = true
      const had = (passed as { context?: readonly string[] }).context ?? []
      return { ...passed, context: [...had, NUDGE] } as never
    }

    isListSeen = true
    const ran = await next(e)
    const outcome = ran as { deny?: string; isError?: boolean; result?: unknown } | undefined
    if (outcome?.deny === undefined && !outcome?.isError) {
      const steps = nextSteps(tool, await read($, plan), args, outcome?.result)
      if (steps) await applySteps($, steps)
    }
    return ran
  })

  on('prompt.submit', async ($, e, next) => {
    turnCalls = 0
    isListSeen = false
    isNudged = false
    return next(e)
  })

  on('agent.spawn', async ($, e, next) => {
    const started = await next(e)
    if (started.deny !== undefined) return started

    const at = await $.clock.now()
    await update($, agents, list => {
      const round = 1 + list.filter(a => norm(a.description) === norm(e.description) && e.description).length
      const run: AgentRun = {
        id: started.agentId ?? e.tool_use_id,
        agentId: started.agentId,
        type: e.subagentType,
        description: e.description,
        model: started.model,
        status: 'running',
        startedAt: at,
        contextTokens: 0,
        contextMax: windowOf(started.model),
        tokens: 0,
        costUsd: 0,
        steps: 0,
        round,
      }
      return [...list.filter(a => a.id !== run.id), run].slice(-200)
    })
    await update($, now, () => at)
    if (options.autoOpen !== 'never') await autoOpen($, 'any-agent')
    return started
  })

  // Each model request of a subagent: live context, tokens and cost.
  on('turn.step', async function* ($, e, next) {
    const result = yield* next(e)
    const agentId = e.agentId
    const usage = result.usage
    if (!agentId || !usage) return result

    const model = usage.model || e.model
    await update($, agents, list =>
      list.map((a): AgentRun =>
        a.agentId !== agentId
          ? a
          : {
              ...a,
              model,
              effort: typeof e.effort === 'string' ? e.effort : a.effort,
              status: 'running',
              endedAt: undefined,
              contextTokens:
                (usage.input_tokens || 0) +
                (usage.cache_read_input_tokens || 0) +
                (usage.cache_creation_input_tokens || 0) +
                (usage.output_tokens || 0),
              contextMax: windowOf(model),
              tokens:
                a.tokens +
                (usage.input_tokens || 0) +
                (usage.output_tokens || 0) +
                (usage.cache_read_input_tokens || 0) +
                (usage.cache_creation_input_tokens || 0),
              costUsd: a.costUsd + costOf(model, usage, true),
              steps: a.steps + 1,
            },
      ),
    )
    return result
  })

  on('turn.complete', async ($, e, next) => {
    const agentId = e.agentId
    if (agentId) {
      const at = await $.clock.now()
      await update($, agents, list =>
        list.map((a): AgentRun => {
          if (a.agentId !== agentId) return a
          // A run whose steps went unseen still gets the turn's own sum.
          const fallback = a.steps === 0 && e.usage
          return {
            ...a,
            status: e.reason === 'answer' ? 'done' : 'failed',
            endedAt: at,
            ...(fallback && e.usage
              ? {
                  model: e.usage.model || a.model,
                  tokens:
                    e.usage.input_tokens +
                    e.usage.output_tokens +
                    e.usage.cache_read_input_tokens +
                    e.usage.cache_creation_input_tokens,
                  costUsd: costOf(e.usage.model || a.model, e.usage, false),
                }
              : {}),
          }
        }),
      )
      await update($, now, () => at)
    }
    return next(e)
  })

  on('ui.render', { component: 'Pane', requestId: PANE }, async ($, e) => {
    const s = tr()
    const ui = $.ui.resolve(e)
    const { Box, Text, Button } = ui
    const list = await read($, agents)
    const f = await read($, flow)
    const p: Panel = await read($, panel)
    const at = Math.max(await read($, now), ...list.map(a => a.startedAt), 0)

    const running = list.filter(a => a.status === 'running').reverse()
    const finished = list.filter(a => a.status !== 'running').reverse()
    const planned = plannedOf(f, list)
    const t = totals(list, at)
    // The pane's title says "Agents"; inside, only the flow's own name.
    const title = f && !f.isFinished ? f.title : ''

    const toggleCompact = (
      <Button
        key="compact"
        label={p.isCompact ? s.expand : s.collapse}
        plain
        onPress={() => update($, panel, prev => ({ ...prev, isCompact: !prev.isCompact }))}
      />
    )
    const toggleDone = (
      <Button
        key="done"
        label={`${p.isDoneCollapsed ? (isRtl() ? '◂' : '▸') : '▾'} ${s.finished} · ${finished.length}`}
        plain
        onPress={() => update($, panel, prev => ({ ...prev, isDoneCollapsed: !prev.isDoneCollapsed }))}
      />
    )
    const isEmpty = list.length === 0 && planned.length === 0
    const summary = `≈${fmtCost(t.cost)}, ${fmtTokens(t.tokens)} ${s.tokensWord}, ${fmtTime(t.time)}`

    if (e.surface === 'desktop' && 'Svg' in ui) {
      const { Svg } = ui
      const W = Math.max(240, Math.min(900, (e.props.bodyColumns || 40) * 8 - 8))
      const section = (key: string, text: string) => (
        <Text key={key} dimColor>
          {text}
        </Text>
      )

      // In Hebrew the column hugs the right edge: section heads and buttons right-aligned.
      const align = isRtl() ? 'flex-end' : undefined
      if (p.isCompact) {
        return (
          <Box flexDirection="column" gap={1} alignItems={align}>
            <Svg source={compactSvg(W, list, planned, t)} alt={`${list.length} ${s.agentsCount}, ${summary}`} width={W} height={32} />
            {toggleCompact}
          </Box>
        )
      }
      const shownDone = p.isDoneCollapsed ? 0 : finished.length
      const lines = 1 + (isEmpty ? 1 : 0) + (running.length > 0 ? 1 : 0) + (finished.length > 0 ? 1 : 0) + (planned.length > 0 ? 1 : 0)
      const gridH = headerHeight(title) + lines * LINE_H + (running.length + shownDone) * 66 + planned.length * 46
      return (
        <Box flexDirection="column">
          {/* The grid sizes the pane; the content is placed over it, as an
              absolute Box paints over the siblings before it. */}
          {gridTiles(gridH).map((tileH, i) => (
            <Svg key={`grid-${i}`} source={gridSvg(W, tileH)} alt="dotted grid" width={W} height={tileH} />
          ))}
          <Box flexDirection="column" position="absolute" top={0} left={0} right={0} alignItems={align}>
            <Svg source={headerSvg(W, title, t)} alt={title ? `${title}: ${summary}` : summary} width={W} height={headerHeight(title)} />
            {toggleCompact}
            {isEmpty && <Text dimColor>{s.empty}</Text>}
            {running.length > 0 && section('h-run', `${s.running} · ${running.length}`)}
            {running.map(a => (
              <Svg key={a.id} source={agentSvg(W, a, at)} alt={`${a.description}: ${modelName(a.model)}, ${s.isRunning}`} width={W} height={66} />
            ))}
            {finished.length > 0 && toggleDone}
            {!p.isDoneCollapsed &&
              finished.map(a => (
                <Svg key={a.id} source={agentSvg(W, a, at)} alt={`${a.description}: ${modelName(a.model)}, ${s.isFinished}`} width={W} height={66} />
              ))}
            {planned.length > 0 && section('h-plan', `${s.planned} · ${planned.length}`)}
            {planned.map(pl => (
              <Svg key={`plan-${pl.n}`} source={plannedSvg(W, pl)} alt={`${pl.n}. ${pl.title}: ${s.isPlanned}`} width={W} height={46} />
            ))}
          </Box>
        </Box>
      )
    }

    // Terminal: the same content in text rows.
    const cols = Math.max(24, e.props.bodyColumns || 40)
    const barW = Math.max(6, Math.min(20, cols - 34))
    const row = (a: AgentRun) => {
      const tier = tierOf(a.type)
      const color = colorOf(tier)
      const ctx = ctxOf(a)
      const progress = progressOf(a)
      const model = runModel(a)
      const steps = a.status === 'running' && a.stepNote ? `${a.stepNote} · ` : ''
      return (
        <Box key={a.id} flexDirection="column" marginBottom={1}>
          <Box flexDirection="row" gap={1}>
            <Text color={color}>▣</Text>
            <Text bold wrap="truncate-end">
              {a.description || a.type}
            </Text>
            <Text color={a.status === 'failed' ? 'red' : a.status === 'done' ? 'green' : color}>{STATUS_GLYPH[a.status]}</Text>
          </Box>
          <Text dimColor wrap="truncate-end">
            {'  '}
            {tier === 'other' ? a.type : tierWord(tier)} · {model}
            {a.round > 1 ? ` · ${s.round} ${a.round}` : ''}
          </Text>
          <Text wrap="truncate-end">
            {'  '}
            {progress === null ? <Text dimColor>{ctxBar(ctx, barW)}</Text> : <Text color={color}>{ctxBar(progress * 100, barW)}</Text>}
            <Text dimColor>
              {' '}
              {steps}{s.ctx} {ctx}% · {fmtTokens(a.contextTokens)} ≈{fmtCost(a.costUsd)} {fmtTime(elapsed(a, at))}
            </Text>
          </Text>
        </Box>
      )
    }

    return (
      <Box flexDirection="column">
        <Box flexDirection="row" justifyContent="space-between">
          <Text bold wrap="truncate-end">
            {title}
          </Text>
          {toggleCompact}
        </Box>
        <Text dimColor>
          ≈{fmtCost(t.cost)} · {fmtTokens(t.tokens)} {s.tokensWord} · {fmtTime(t.time)}
        </Text>
        {p.isCompact ? (
          <Text wrap="truncate-end">
            {[...running, ...finished].map(a => (
              <Text key={a.id} color={colorOf(tierOf(a.type))}>
                {STATUS_GLYPH[a.status]}{' '}
              </Text>
            ))}
            {planned.map(pl => (
              <Text key={`plan-${pl.n}`} dimColor>
                ◷{' '}
              </Text>
            ))}
          </Text>
        ) : (
          <Box flexDirection="column" marginTop={1}>
            {isEmpty && <Text dimColor>{s.empty}</Text>}
            {running.length > 0 && <Text dimColor>{s.running} · {running.length}</Text>}
            {running.map(row)}
            {finished.length > 0 && toggleDone}
            {!p.isDoneCollapsed && finished.map(row)}
            {planned.length > 0 && <Text dimColor>{s.planned} · {planned.length}</Text>}
            {planned.map(pl => {
              const tier = pl.tier in TIER_COLOR ? pl.tier : 'other'
              return (
                <Box key={`plan-${pl.n}`} flexDirection="column" marginBottom={1}>
                  <Text dimColor wrap="truncate-end">
                    <Text color={colorOf(tier)}>▢</Text> {pl.n}. {pl.title} ◷
                  </Text>
                  <Text dimColor wrap="truncate-end">
                    {'  '}
                    {tierWord(tier)} · {tierModel(tier)}
                    {pl.after.length ? ` · ${s.after} ${pl.after.join(', ')}` : ''}
                  </Text>
                </Box>
              )
            })}
          </Box>
        )}
      </Box>
    )
  })

  on('ui.render', { component: 'AbovePrompt' }, async ($, e, next) => {
    // Inside Le Fluff the row is handed over as a drawing (see handOver), so the terminal draws none of its own.
    if (leFluff && e.surface === 'terminal') {
      columns = e.props.bodyColumns || columns
      return next(e)
    }
    const f = await read($, flow)
    if (f === null || e.props.hasSurvey) return next(e)
    // Draw this row with the other mods' bands beneath it. Claude Code's own placeholder ({ type: 'engine' }) is
    // never nested: the desktop drops a band that nests it.
    const drawn = await Promise.resolve(next(e)).catch(() => null)
    const below = drawn && typeof drawn === 'object' && (drawn as { type?: string }).type !== 'engine' ? drawn : null

    const ui = $.ui.resolve(e)
    const { Box, Text, Button } = ui
    const list = await read($, agents)
    const crew = list.length + plannedOf(f, list).length
    const isWorking = list.some(a => a.status === 'running') || (!f.isFinished && f.running > 0)
    const crewButton = (
      <Button key="desk-agents" label={`×${crew}`} plain onPress={() => void togglePane($)} />
    )
    const percent = `${Math.round(ratio(f) * 100)}%`
    const dismiss = (
      <Button
        key="desk-dismiss"
        label="✕"
        plain
        role="dismiss"
        onPress={() => update($, flow, () => null)}
      />
    )

    // The terminal's element table is completed with an `Svg` that draws nothing: test the surface too.
    if (e.surface !== 'terminal' && 'Svg' in ui) {
      const { Svg } = ui
      // About 8 CSS px per reported column; the rest is the count, the dismiss
      // and their gaps. No floor above the slot: a row wider than it would wrap.
      const width = Math.max(180, Math.min(1600, (e.props.bodyColumns || 100) * 8 - 96))
      return (
        <Box flexDirection="column">
          <Box flexDirection={isRtl() ? 'row-reverse' : 'row'} alignItems="center" gap={1}>
            <Svg source={rowSvg(f, width, isWorking)} alt={`${f.title}: ${label(f)}, ${percent}`} width={width} height={H} />
            {crewButton}
            {dismiss}
          </Box>
          {below}
        </Box>
      )
    }

    const cols = e.props.bodyColumns
    const titleW = Math.max(8, Math.min(30, f.title.length + 2, Math.floor(cols / 3)))
    const width = Math.max(6, Math.min(40, cols - titleW - 32))
    return (
      <Box flexDirection="column">
        <Box flexDirection="row" gap={2}>
          <Box width={titleW} flexShrink={0}>
            <Text color={f.isFinished ? DONE : ACCENT}>● </Text>
            <Text wrap="truncate-end">{f.title}</Text>
          </Box>
          <Text color={f.isFinished ? DONE : ACCENT}>{barText(f, width)}</Text>
          <Text bold>{label(f)}</Text>
          <Text dimColor>{percent}</Text>
          <Text color={CLAY}>▣</Text>
          {crewButton}
          {dismiss}
        </Box>
        {below}
      </Box>
    )
  })
}
