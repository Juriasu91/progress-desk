const oneLine = (v: unknown): string => (typeof v === 'string' ? v.replace(/\s+/g, ' ').trim() : '')
const statusOf = (v: unknown): PlanStatus => (v === 'in_progress' || v === 'completed' ? v : 'pending')

const fromItems = (items: unknown[]): PlanStep[] =>
  items
    .flatMap((raw): PlanStep[] => {
      const item = (raw && typeof raw === 'object' ? raw : {}) as Args
      const text = oneLine(item.content)
      return text ? [{ text, status: statusOf(item.status) }] : []
    })
    .slice(0, MAX_TASKS)

// The desktop app's task list: a whole new list, or a change to the current one.
const fromPlanCall = (prev: PlanStep[], args: Args): PlanStep[] | null => {
  if (Array.isArray(args.items)) return fromItems(args.items)
  const steps = prev.map(step => ({ ...step }))
  if (args.advance === true) {
    const at = steps.findIndex(step => step.status === 'in_progress')
    if (at >= 0) steps[at]!.status = 'completed'
    const next = steps.find(step => step.status === 'pending')
    if (next) next.status = 'in_progress'
  }
  for (const n of Array.isArray(args.done) ? args.done : []) {
    const step = steps[Number(n) - 1]
    if (step) step.status = 'completed'
  }
  const started = steps[Number(args.start) - 1]
  if (started) started.status = 'in_progress'
  return steps
}

const fromTaskUpdate = (prev: PlanStep[], args: Args): PlanStep[] | null => {
  const id = oneLine(args.taskId)
  const at = prev.findIndex(step => step.id === id)
  if (args.status === 'deleted') return at >= 0 ? prev.filter((_, i) => i !== at) : null
  const subject = oneLine(args.subject)
  if (at < 0) return subject ? [...unfinished(prev), { text: subject, status: statusOf(args.status), id }] : null
  return prev.map((step, i) =>
    i === at
      ? { ...step, ...(subject ? { text: subject } : {}), ...(args.status ? { status: statusOf(args.status) } : {}) }
      : step,
  )
}

// A finished list is over: the next task starts a new one.
const unfinished = (steps: PlanStep[]): PlanStep[] => (steps.every(step => step.status === 'completed') ? [] : steps)

// The new list after a list tool's call, or null when the call changes nothing.
const nextSteps = (tool: string, prev: PlanStep[], args: Args, result: unknown): PlanStep[] | null => {
  if (tool === OWN_TOOL) {
    if (!Array.isArray(args.steps)) return null
    return fromItems(args.steps.map(step => ({ content: (step as Args)?.text, status: (step as Args)?.status })))
  }
  if (tool === PLAN_TOOL) return fromPlanCall(prev, args)
  if (tool === WRAP_TOOL) return prev.length ? prev.map(step => ({ ...step, status: 'completed' })) : null
  if (tool === 'TodoWrite') return Array.isArray(args.todos) ? fromItems(args.todos) : null
  if (tool === 'TaskUpdate') return fromTaskUpdate(prev, args)
  const text = oneLine(args.subject)
  if (!text) return null
  const id = (result as { task?: { id?: unknown } } | undefined)?.task?.id
  return [...unfinished(prev), { text, status: 'pending', ...(typeof id === 'string' ? { id } : {}) }]
}

const toFlow = (steps: PlanStep[]): Flow | null => {
  if (steps.length === 0) return null
  const done = steps.filter(step => step.status === 'completed').length
  const running = steps.filter(step => step.status === 'in_progress').length
  const shown = steps.find(step => step.status === 'in_progress') ?? steps.find(step => step.status === 'pending') ?? steps[steps.length - 1]
  return {
    title: clip(shown?.text ?? '', MAX_TITLE),
    total: steps.length,
    done,
    running,
    phase: 'delegate',
    isFinished: done === steps.length,
    tasks: [],
  }
}

let holdTimer: { cancel: () => void } | null = null

async function applySteps($: EngineInterface, steps: PlanStep[]): Promise<void> {
  await update($, plan, () => steps)
  const shown = toFlow(steps)
  await update($, flow, () => shown)
  holdTimer?.cancel()
  holdTimer = null
  // Inside a Le Fluff that draws this mod's buttons, a finished list stays until its ✕ is pressed there.
  if (shown?.isFinished && !hasButtons) {
    holdTimer = $.clock.after(HOLD_MS, () => {
      holdTimer = null
      void update($, flow, () => null)
    })
  }
}

// What a subagent is doing, in a few words, read from the tool call it just made.
const fileName = (p: string): string => p.split(/[\\/]/).filter(Boolean).pop() ?? 'a file'

const activity = (tool: string, args: Args): string => {
  const file = (verb: string, key = 'file_path') => `${verb} ${fileName(oneLine(args[key]))}`
  if (tool.startsWith('mcp__')) return `Using ${(tool.split('__').pop() ?? tool).replace(/[-_]+/g, ' ')}`
  switch (tool) {
    case 'Read':
      return file('Reading')
    case 'Write':
      return file('Writing')
    case 'Edit':
    case 'MultiEdit':
      return file('Editing')
    case 'NotebookEdit':
      return file('Editing', 'notebook_path')
    case 'Grep':
    case 'Glob':
      return oneLine(args.pattern) ? `Searching for "${clip(oneLine(args.pattern), 40)}"` : 'Searching files'
    case 'Bash':
    case 'PowerShell':
      return oneLine(args.description) ? `Running: ${oneLine(args.description)}` : 'Running a command'
    case 'WebSearch':
      return `Searching the web: ${oneLine(args.query)}`
    case 'WebFetch':
      return `Opening ${/^https?:\/\/([^/]+)/.exec(oneLine(args.url))?.[1] ?? 'a web page'}`
    case 'Skill':
      return `Using the ${oneLine(args.skill) || 'a'} skill`
    case 'Agent':
    case 'Task':
      return 'Starting a subagent'
    default:
      return `Using ${tool}`
  }
}

const label = (f: Flow): string => {
  const s = tr()
  if (f.isFinished) return s.done
  if (f.phase === 'plan') return s.plan
  if (f.phase === 'design') return s.design
  const count = f.total ? `${f.done}/${f.total}` : `${f.running} ${s.busy}`
  return `${f.phase === 'review' ? s.review : s.tasks} ${count}`
}

const ratio = (f: Flow): number => (f.isFinished ? 1 : f.total ? f.done / f.total : 0)

// Deterministic noise so the dither does not shimmer between redraws.
const noise = (x: number, y: number): number => {
  const s = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453
  return s - Math.floor(s)
}

